-- Ejecutar en Supabase SQL Editor ANTES de activar los recordatorios de WhatsApp en el backend.
--
-- Plantilla requerida en Meta WhatsApp Manager (categoría: UTILITY):
--   Nombre sugerido (WHATSAPP_TEMPLATE_NAME): aviso_cuota_bingo
--   Idioma sugerido (WHATSAPP_TEMPLATE_LANG): es_AR
--   Parámetros del cuerpo (body):
--     {{1}} -> Nombre y apellido del comprador (ej.: "María González")
--     {{2}} -> Número de bingo (ej.: "104")
--     {{3}} -> Detalle de cuotas vencidas (ej.: "Cuota 1 (Marzo), Cuota 2 (Abril)")
--   Recomendación Meta T&Cs: incluir pie de página o botón rápido indicando que puede
--   responder "BAJA" para dejar de recibir recordatorios automáticos.

BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'bingos_late_payment_notice_check'
    ) THEN
        ALTER TABLE public.bingos
            ADD CONSTRAINT bingos_late_payment_notice_check
            CHECK (late_payment_notice >= 0 AND late_payment_notice <= 31);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.whatsapp_bingo_notices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bingo_id bigint NOT NULL REFERENCES public.bingos(id) ON DELETE CASCADE,
    period_year smallint NOT NULL,
    period_month smallint NOT NULL CHECK (period_month >= 1 AND period_month <= 12),
    scheduled_date date NOT NULL,
    recipient_phone character varying(20) NOT NULL,
    late_quotes_mask smallint NOT NULL,
    status character varying(24) NOT NULL CHECK (
        status IN (
            'processing',
            'sent',
            'delivered',
            'read',
            'transient_error',
            'failed',
            'unknown'
        )
    ),
    provider_message_id text,
    attempts smallint NOT NULL DEFAULT 1 CHECK (attempts >= 1),
    next_retry_at timestamptz,
    last_error_code character varying(64),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT whatsapp_bingo_notices_unique_period UNIQUE (bingo_id, period_year, period_month)
);

CREATE INDEX IF NOT EXISTS whatsapp_bingo_notices_period_status_idx
    ON public.whatsapp_bingo_notices (period_year, period_month, status);

CREATE INDEX IF NOT EXISTS whatsapp_bingo_notices_provider_msg_idx
    ON public.whatsapp_bingo_notices (provider_message_id)
    WHERE provider_message_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.whatsapp_opt_outs (
    phone_e164 character varying(20) PRIMARY KEY,
    reason character varying(64) NOT NULL DEFAULT 'user_reply',
    opted_out_at timestamptz NOT NULL DEFAULT now()
);

-- Acceso exclusivo del backend, nunca desde el cliente de Supabase del navegador.
ALTER TABLE public.whatsapp_bingo_notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_opt_outs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.whatsapp_bingo_notices FROM PUBLIC;
REVOKE ALL ON public.whatsapp_opt_outs FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.whatsapp_bingo_notices FROM anon;
        REVOKE ALL ON public.whatsapp_opt_outs FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.whatsapp_bingo_notices FROM authenticated;
        REVOKE ALL ON public.whatsapp_opt_outs FROM authenticated;
    END IF;
END $$;

COMMIT;
