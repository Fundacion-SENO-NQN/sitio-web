/* ==========================================================
   STANDARDIZED MODULE SELECTORS

   Matches the IDs generated by:
   - Plataforma/ControlTabla.astro
   - Plataforma/Tabla.astro
   - Plataforma/ModalFormulario.astro
   - Plataforma/ModalEliminar.astro
========================================================== */

export function getModuleSelectors(servicio, servicioPlural = `${servicio}s`) {
  if (!servicio || typeof servicio !== 'string') {
    throw new TypeError('getModuleSelectors requires a valid servicio name.')
  }

  return {
    /* Toolbar */
    searchInput: `#buscar-${servicioPlural}`,
    countElement: `#cantidad-${servicioPlural}`,
    newButton: `#btn-nuevo-${servicio}`,

    /* Table & states */
    loadingElement: `#estado-cargando-${servicio}`,
    errorElement: `#estado-error-${servicio}`,
    emptyElement: `#estado-vacio-${servicio}`,
    tableWrapper: `#tabla-wrapper-${servicio}`,
    tableBody: `#tbody-${servicio}`,
    retryButton: `#btn-reintentar-${servicio}`,
    emptyCreateButton: `#btn-primer-${servicio}`,
    sortableHeadersSelector: `[data-sort-servicio="${servicio}"][data-sort-key]`,

    /* Create / Edit modal */
    formModal: `#modal-${servicio}`,
    form: `#form-${servicio}`,
    formModalTitle: `#modal-${servicio}-titulo`,
    saveButton: `#btn-guardar-${servicio}`,
    closeFormModalButton: `#btn-cerrar-modal-${servicio}`,
    cancelFormModalButton: `#btn-cancelar-${servicio}`,
    formModalBackdrop: `[data-cerrar-modal="${servicio}"]`,

    /* Delete modal */
    deleteModal: `#modal-eliminar-${servicio}`,
    deleteModalTitle: `#modal-eliminar-${servicio}-titulo`,
    deleteText: `#texto-eliminar-${servicio}`,
    confirmDeleteButton: `#btn-confirmar-eliminar-${servicio}`,
    cancelDeleteButton: `#btn-cancelar-eliminar-${servicio}`,
    closeDeleteButton: `#btn-cerrar-modal-eliminar-${servicio}`,
    deleteModalBackdrop: `[data-cerrar-modal-eliminar="${servicio}"]`
  }
}

/**
 * Discovers any `<th data-sort-servicio="..." data-sort-key="...">` headers
 * rendered by `Tabla.astro` and maps `{ [sortKey]: element }` for `listController`.
 */
export function resolveTableSortHeaders(
  servicio,
  root = typeof document !== 'undefined' ? document : null
) {
  if (!root) return {}

  const headers = root.querySelectorAll(
    `[data-sort-servicio="${servicio}"][data-sort-key]`
  )

  const sortButtons = {}

  headers.forEach((header) => {
    const key = header.dataset.sortKey

    if (key) {
      sortButtons[key] = header
    }
  })

  return sortButtons
}

/* ==========================================================
   GENERIC CRUD MODULE ORCHESTRATOR

   Connects API + List + Table + Form Modal + Delete Modal
   (+ optional Order controller) for any platform service.
========================================================== */

export function createPlatformCrudModule({
  servicio,
  servicioPlural = `${servicio}s`,

  api,

  /* List options */
  searchValues,
  sorters = undefined,
  defaultSort = undefined,
  defaultAscending = true,
  sortButtons = undefined,
  messages = {},

  /* Table options */
  columns,
  createColumns = null,
  tableOptions = {},

  /* Modal options */
  modalOptions = {},

  /* Delete options */
  deleteOptions = {},

  /* Optional order options */
  enableOrder = false,
  orderOptions = {},

  /* Lifecycle hooks */
  requireAuth = true,
  onInit = null,
  onUnauthorized = defaultHandleUnauthorized,
  notify = showToast,

  /* Optional selector overrides */
  selectors: selectorOverrides = {}
} = {}) {
  if (!servicio) {
    throw new TypeError('createPlatformCrudModule requires "servicio".')
  }

  if (!api || typeof api.list !== 'function') {
    throw new TypeError('createPlatformCrudModule requires a valid CRUD "api".')
  }

  const selectors = {
    ...getModuleSelectors(servicio, servicioPlural),
    ...selectorOverrides
  }

  let renderTable = () => {}

  const discoveredSortButtons =
    sortButtons ?? resolveTableSortHeaders(servicio)

  const listController = createListController({
    load: api.list,

    render(context) {
      renderTable(context)
    },

    searchInput: selectors.searchInput,
    countElement: selectors.countElement,

    loadingElement: selectors.loadingElement,
    errorElement: selectors.errorElement,
    emptyElement: selectors.emptyElement,
    tableElement: selectors.tableWrapper,

    retryButton: selectors.retryButton,
    createButtons: [selectors.newButton, selectors.emptyCreateButton],

    onCreate() {
      formModal.openCreate()
    },

    searchValues,
    sorters,
    defaultSort,
    defaultAscending,
    sortButtons: discoveredSortButtons,

    singular: servicio,
    plural: servicioPlural,

    messages: {
      loadError: `No se pudieron cargar los ${servicioPlural}.`,
      ...messages
    },

    onError(error) {
      if (error?.status === 401 && typeof onUnauthorized === 'function') {
        onUnauthorized(error)
        return
      }

      notify(
        error instanceof Error
          ? error.message
          : `No se pudieron cargar los ${servicioPlural}.`,
        'error'
      )
    }
  })

  const orderController = enableOrder
    ? createOrderController({
        listController,
        changeOrder: api.changeOrder,
        refresh: listController.refresh,
        optimistic: true,
        refreshAfterChange: true,
        refreshAfterError: true,
        errorMessage: `No se pudo cambiar el orden de los ${servicioPlural}.`,
        ...orderOptions
      })
    : null

  const formModal = createFormModalController({
    modal: selectors.formModal,
    form: selectors.form,
    titleElement: selectors.formModalTitle,
    saveButton: selectors.saveButton,
    closeButtons: [selectors.closeFormModalButton],
    cancelButtons: [selectors.cancelFormModalButton],
    backdrop: selectors.formModalBackdrop,
    hiddenClass: 'oculto',

    createTitle: `Nuevo ${servicio}`,
    editTitle: `Editar ${servicio}`,
    createButtonText: `Guardar ${servicio}`,
    editButtonText: 'Guardar cambios',
    creatingText: `Creando ${servicio}...`,
    updatingText: 'Guardando cambios...',
    createSuccessMessage: `El ${servicio} fue creado correctamente.`,
    updateSuccessMessage: `El ${servicio} fue actualizado correctamente.`,
    errorMessage: `No se pudo guardar el ${servicio}.`,

    create: api.create,
    update: api.update,
    refresh: listController.refresh,
    disableFormWhileSubmitting: true,
    notify,

    ...modalOptions
  })

  const deleteController = createDeleteController({
    modal: selectors.deleteModal,
    confirmButton: selectors.confirmDeleteButton,
    cancelButtons: [selectors.cancelDeleteButton],
    closeButtons: [selectors.closeDeleteButton],
    backdrop: selectors.deleteModalBackdrop,
    textElement: selectors.deleteText,
    hiddenClass: 'oculto',
    focusElement: selectors.cancelDeleteButton,

    remove: api.remove,
    refresh: listController.refresh,

    deletingText: `Eliminando ${servicio}...`,
    confirmButtonText: `Eliminar ${servicio}`,
    successMessage: `El ${servicio} fue eliminado correctamente.`,
    errorMessage: `No se pudo eliminar el ${servicio}.`,
    notify,

    ...deleteOptions
  })

  const resolvedColumns =
    typeof createColumns === 'function'
      ? createColumns({
          listController,
          orderController,
          formModal,
          deleteController,
          onEdit: (item) => formModal.openEdit(item),
          onDelete: (item) => deleteController.open(item)
        })
      : columns

  renderTable = createTableRenderer({
    body: selectors.tableBody,
    columns: resolvedColumns,
    ...tableOptions
  })

  async function initialize() {
    if (
      requireAuth &&
      typeof window !== 'undefined' &&
      !window.localStorage?.getItem('token')
    ) {
      forceHideLoadingScreen()
      if (typeof onUnauthorized === 'function') {
        onUnauthorized(null)
      }
      return
    }

    try {
      if (typeof onInit === 'function') {
        await onInit({
          selectors,
          listController,
          orderController,
          formModal,
          deleteController
        })
      }

      formModal.initialize()
      deleteController.initialize()

      await listController.initialize()
    } catch (error) {
      console.error(
        `Falló la inicialización del módulo "${servicio}":`,
        error
      )
    } finally {
      if (!isLoading()) {
        forceHideLoadingScreen()
      }
    }
  }

  function destroy() {
    listController.destroy()
    formModal.destroy()
    deleteController.destroy()
  }

  return {
    selectors,
    listController,
    orderController,
    formModal,
    deleteController,
    initialize,
    destroy
  }
}

function defaultHandleUnauthorized() {
  if (typeof window !== 'undefined') {
    window.location.replace('/login/')
  }
}
